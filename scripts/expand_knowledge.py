def main():
    data = json.loads(DATA.read_text(encoding='utf-8'))

    have_q = {f['question'] for f in data['faq']}
    for q, a in FAQ:
        if q not in have_q:
            data['faq'].append({'question': q, 'answer': a})

    have_g = {g['term'] for g in data['glossary']}
    for term, definition in GLOSSARY:
        if term not in have_g:
            data['glossary'].append({'term': term, 'def': definition})

    have_r = set(data['redFlags'])
    for r in RED_FLAGS:
        if r not in have_r:
            data['redFlags'].append(r)

    t7 = data['types'][6]
    for paragraph in TYPE7_EXTRA:
        if paragraph not in t7['paragraphs']:
            t7['paragraphs'].append(paragraph)

    data['stats'][2]['value'] = str(len(data['faq']))
    data['quickCards'][1]['text'] = f"{len(data['faq'])} 个学生高频问题，支持关键词即时检索。"

    DATA.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    JS.write_text('window.ANTIFRAUD_CONTENT = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n',
                  encoding='utf-8')
    print('faq', len(data['faq']), '| glossary', len(data['glossary']),
          '| redFlags', len(data['redFlags']), '| type7 paras', len(t7['paragraphs']))


if __name__ == '__main__':
    main()
